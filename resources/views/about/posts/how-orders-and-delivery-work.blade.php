<p>
    Every order follows the same path from the catalogue to delivery. Knowing the steps makes it easier to track an order and
    raise a support request if something does not go to plan.
</p>

<h2>From cart to order</h2>
<ul>
    <li>Products are added to the cart from the Super Mall.</li>
    <li>Checkout confirms the delivery details and the total in Ghana cedis.</li>
    <li>Payment is taken from the customer wallet balance.</li>
    <li>The order is created with a reference and appears in the account order history.</li>
</ul>

<h2>Delivery</h2>
<p>
    Delivery timelines depend on the product and the delivery location. The delivery details shown at checkout apply to that
    order. Customers should provide a reachable phone number and a complete address so the delivery team can make contact.
</p>

<h2>Order status</h2>
<p>
    Orders move through a visible status flow, from payment confirmation to fulfilment and delivery. The order page in the
    customer account shows the current status and the order reference.
</p>

<h2>Returns and support</h2>
<p>
    Returns are handled under the published returns policy. Keep the order reference and the item packaging until the order is
    confirmed. For a delivery issue, contact support with the order reference so the team can locate the order quickly.
</p>
