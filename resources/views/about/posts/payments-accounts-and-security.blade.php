<p>
    Payments and account access are handled inside the customer account. This page explains how the payment flow works, what
    the wallet is for and the steps customers should take to keep an account secure.
</p>

<h2>Payment processing</h2>
<p>
    Wallet top-ups are processed by Paystack. The payment provider confirms the transaction before the wallet balance is
    updated. Customers should keep the payment reference shown after a top-up until the balance appears in the account.
</p>

<h2>Why the wallet exists</h2>
<p>
    The wallet gives customers one balance for data, shopping and services. Payments from the wallet are recorded against the
    order, so the account shows what was paid and what was bought in one place.
</p>

<h2>Account security</h2>
<ul>
    <li>Use a strong password and keep it private.</li>
    <li>Sign out when using a shared device.</li>
    <li>Check the account notifications for unexpected activity.</li>
    <li>Contact support immediately if a payment or order looks unfamiliar.</li>
</ul>

<h2>Support with a payment</h2>
<p>
    When contacting support about a payment, include the order reference and the payment reference. That information lets the
    team trace the transaction without requesting sensitive banking details.
</p>
